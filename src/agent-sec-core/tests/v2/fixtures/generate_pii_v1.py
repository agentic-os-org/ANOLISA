UNICODE_OUTPUT = OUTPUT.parents[2] / "src/python_unicode.rs"


def freeze_character_classes() -> dict[str, str]:
    """Freeze Python's character semantics independently of Rust's Unicode version."""
    if unicodedata.unidata_version != "14.0.0":
        raise RuntimeError("builtin character classes require Unicode 14.0.0")
    lines = [
        "//! Python 3.11.6 / Unicode 14.0.0 character classes for builtin rules.",
        "//! Generated by `tests/v2/fixtures/generate_pii_v1.py`; do not edit by hand.",
        "",
    ]
    hashes = {}
    for name, predicate in [
        ("WORD", lambda c: c == "_" or c.isalnum()),
        ("DECIMAL", str.isdecimal),
    ]:
        ranges: list[tuple[int, int]] = []
        classifications = bytearray()
        for code in range(0x110000):
            if 0xD800 <= code <= 0xDFFF:
                continue
            matched = predicate(chr(code))
            classifications.append(int(matched))
            if matched:
                if ranges and ranges[-1][1] == code - 1:
                    ranges[-1] = (ranges[-1][0], code)
                else:
                    ranges.append((code, code))
        hashes[name.lower()] = hashlib.sha256(classifications).hexdigest()
        lines += [f"pub(super) const {name}_RANGES: &[(char, char)] = &["]
        lines += [
            f"    ('\\u{{{start:x}}}', '\\u{{{end:x}}}')," for start, end in ranges
        ]
        lines += ["];", ""]
    UNICODE_OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    hashes["decimal_values"] = hashlib.sha256(
        bytes(
            unicodedata.decimal(chr(code), 255)
            for code in range(0x110000)
            if not 0xD800 <= code <= 0xDFFF
        )
    ).hexdigest()
    return hashes


class Recorder:
    """Capture calls through v1's test helper without replacing its assertions."""

    def __init__(self) -> None:
        self.records: dict[str, dict[str, Any]] = {}
        self.scan: Callable[..., dict[str, Any]] | None = None

    def pytest_runtest_setup(self, item: Any) -> None:
        module = item.module
        scan = getattr(module, "_scan", None)
        if scan is None or getattr(scan, "_capturing", False):
            return

        @functools.wraps(scan)
        def record(text: str, **kwargs: Any) -> dict[str, Any]:
            result = scan(text, **kwargs)
            # Large-input limits have separate bounded Rust tests. Keeping the
            # golden corpus small makes every expected finding reviewable.
            if len(text.encode("utf-8")) <= 65536:
                expected = json.loads(json.dumps(result))
                expected.pop("elapsed_ms")
                key = json.dumps([text, kwargs], sort_keys=True, ensure_ascii=False)
                self.records[key] = {
                    "text": text,
                    "options": kwargs,
                    "expected": expected,
                }
            return result

        record._capturing = True
        module._scan = record
        self.scan = record


