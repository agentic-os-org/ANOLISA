/// Generates a JSON array with `n` response items from the canonical records.
/// If `n` exceeds the fixture's record count (1000), silently truncates to 1000.
pub fn response_items(n: usize) -> Value {
    Value::Array(records().iter().take(n).cloned().collect())
}

/// Focused record collection with a critical anomaly at index 31.
pub fn response_record_reduction() -> Value {
    serde_json::from_str(RECORD_REDUCTION_JSON)
        .expect("fixtures/record_reduction.json is valid JSON")
}

/// A ~1MB response — the canonical records cycled to fill approximately one
/// megabyte of serialized JSON. The 1000-record fixture (~326KB) is repeated
/// ~3.2× to reach the target size.
pub fn response_huge() -> Value {
    let recs = records();
    // Each record is ~326 bytes serialized; 3200 records ≈ 1,043,200 bytes ≈ 1MB.
    let items: Vec<Value> = recs.iter().cycle().take(3200).cloned().collect();
    Value::Array(items)
}

/// The canonical tool response (`fixtures/tool_response.json`): a synthetic
/// compression-friendly fixture (an envelope wrapping 60 records plus
/// trace/log noise). Designed to exercise field deletion (debug/trace/logs)
/// without changing its record count — does NOT represent typical
/// tool-response compression rates.
///
/// Measured for BOTH latency (here) and compression rate (Rust in-process),
/// so the two numbers describe the same bytes.
pub fn response_canonical() -> Value {
    serde_json::from_str(TOOL_RESPONSE_JSON).expect("fixtures/tool_response.json is valid JSON")
}

/// The canonical function-calling schema (`fixtures/schema_search.json`),
/// measured for BOTH schema-compression latency and compression rate.
pub fn schema_canonical() -> Value {
    serde_json::from_str(SCHEMA_SEARCH_JSON).expect("fixtures/schema_search.json is valid JSON")
}

/// A response with one very long string field (`chars` characters).
pub fn response_long_string(chars: usize) -> Value {
    json!({ "log": "x".repeat(chars) })
}

/// An object nested `depth` levels deep under repeated `child` keys.
pub fn response_deep_nesting(depth: usize) -> Value {
    let mut v = json!({ "leaf": "value" });
    for _ in 0..depth {
        v = json!({ "child": v });
    }
    v
}

/// A response with a highly repetitive array — the same record repeated `n`
/// times — to probe how repetition interacts with truncation.
pub fn response_high_repetition(n: usize) -> Value {
    let one = json!({ "kind": "event", "code": 200, "note": "repeated payload" });
    Value::Array(vec![one; n])
}

