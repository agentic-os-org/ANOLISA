//! Shared fixture generators for the tokenless benchmark suite.
//!
//! This crate currently covers **L1 — the component layer** of the
//! four-layer tokenless benchmark plan: every bench and test measures one
//! compressor (schema, response, TOON, RTK rewrite) in isolation, which is
//! why all bench/test targets carry the `l1_` prefix. Higher layers (L2
//! module-level comparison and beyond) land separately under their own
//! prefixes.
//!
//! Every benchmark and quality/adversarial test draws its inputs from here so
//! the same synthetic payloads back both the latency numbers and the
//! correctness assertions. Keeping generation deterministic (no RNG) makes
//! criterion runs comparable across machines and reruns.
//!
//! The `canonical` inputs (`response_items`, `response_canonical`,
//! `schema_canonical`) load committed fixtures generated by
//! `python/gen_fixtures.py`, so the Rust latency numbers and the Python
//! compression-rate numbers are measured on byte-identical payloads.
//! Compression rates themselves are computed in-process in [`metrics`] by
//! counting tokens immediately before and after each compressor call.

pub mod metrics;

use serde_json::{Map, Value, json};
use std::sync::OnceLock;
use tokenless_ccr::StashStore;
use tokenless_compressors::{
    JsonCompressionConfig, JsonCompressionContext, JsonCompressor, JsonOutcome, RecoveryMethod,
};

/// Runs the default JSON compressor and parses its JSON representation.
pub fn compress_json(value: &Value) -> Value {
    compress_json_with(value, JsonCompressionConfig::default(), None).0
}

/// Runs the JSON compressor with explicit limits and an optional Stash store.
///
/// [`RecoveryMethod::Shell`] matches the default CLI recovery entry point so
/// Stash-backed tests exercise its instruction format and truncation budget.
/// Without a Stash (including the current latency benches), the recovery method
/// does not affect output or compression metrics.
pub fn compress_json_with(
    value: &Value,
    config: JsonCompressionConfig,
    stash: Option<&dyn StashStore>,
) -> (Value, JsonOutcome) {
    let input = serde_json::to_string(value).expect("JSON value serializes");
    let outcome = JsonCompressor::new(config)
        .compress(
            &input,
            &JsonCompressionContext {
                recovery: &RecoveryMethod::Shell,
                stash,
                allow_toon: false,
                preserve_top_level_shape: false,
                min_toon_chars: usize::MAX,
                allow_unrecoverable: true,
            },
        )
        .expect("serialized JSON value parses");
    let output = serde_json::from_str(&outcome.output).expect("JSON compressor emitted JSON");
    (output, outcome)
}

// Canonical fixtures generated by `python/gen_fixtures.py`. Embedding them with
// `include_str!` keeps the Rust latency benches and the Python compression-rate
// scripts on byte-identical input — the whole point of the shared generator —
// without adding a build-time codegen step. The strings are compile-time
// constants we control, so `expect` on parse cannot fire for a committed
// fixture; a failure here means the fixture file was hand-edited into invalid
// JSON, which should surface loudly.
const RECORDS_JSON: &str = include_str!("../fixtures/records.json");
const RECORD_REDUCTION_JSON: &str = include_str!("../fixtures/record_reduction.json");
const TOOL_RESPONSE_JSON: &str = include_str!("../fixtures/tool_response.json");
const SCHEMA_SEARCH_JSON: &str = include_str!("../fixtures/schema_search.json");

/// Parsed, cached canonical records. Backs `response_items` so the latency
/// curve runs on the same records the Python scripts compress.
fn records() -> &'static [Value] {
    static CACHE: OnceLock<Vec<Value>> = OnceLock::new();
    CACHE.get_or_init(|| match serde_json::from_str::<Value>(RECORDS_JSON) {
        Ok(Value::Array(items)) => items,
        _ => panic!("fixtures/records.json must be a JSON array of records"),
    })
}

/// A minimal OpenAI function-calling schema with `n` string parameters.
///
/// Used by schema latency/retention benches. Each parameter carries a short
/// description so the compressor has real work to do.
pub fn schema_with_params(n: usize) -> Value {
    let mut props = Map::new();
    for i in 0..n {
        props.insert(
            format!("param_{i}"),
            json!({
                "type": "string",
                "description": format!("Parameter number {i}. A short human-readable hint.")
            }),
        );
    }
    json!({
        "function": {
            "name": "example_tool",
            "description": "An example tool used to exercise schema compression.",
            "parameters": { "type": "object", "properties": props }
        }
    })
}

/// A schema whose function/param descriptions are long enough to force
/// truncation (well past the 256/160 defaults).
pub fn schema_long_description() -> Value {
    let long = "This is a deliberately verbose description. ".repeat(40);
    json!({
        "function": {
            "name": "verbose_tool",
            "description": long.clone(),
            "parameters": {
                "type": "object",
                "properties": {
                    "field": { "type": "string", "description": long }
                }
            }
        }
    })
}

/// A deeply-structured schema with exponential branching: `fields` top-level
/// properties, each nested `depth` levels via both `anyOf` and
/// `properties.child` at every level — producing 2^depth leaves per field
/// (exponential fan-out, not a linear chain).
pub fn schema_complex(fields: usize, depth: usize) -> Value {
    // Leaf/branch descriptions (~105–106 chars) are within the default
    // 160-char limit; truncation triggers only with lower thresholds.
    fn nest(depth: usize) -> Value {
        if depth == 0 {
            return json!({
                "type": "string",
                "title": "Leaf",
                "examples": ["a", "b"],
                "description": "Leaf description providing context about this terminal node in the schema tree, padded to a realistic length for benchmarking."
            });
        }
        json!({
            "type": "object",
            "title": "Branch",
            "description": "Branch description providing context about this intermediate node, padded with extra words to reach a realistic parameter length.",
            "anyOf": [ nest(depth - 1) ],
            "properties": { "child": nest(depth - 1) }
        })
    }
    let mut props = Map::new();
    for i in 0..fields {
        props.insert(format!("f_{i}"), nest(depth));
    }
    json!({
        "function": {
            "name": "complex_tool",
            "description": "Complex tool description.",
            "parameters": { "type": "object", "properties": props }
        }
    })
}

/// A batch (JSON array) of `n` uniform simple schemas (3 params each).
pub fn schema_batch(n: usize) -> Value {
    Value::Array((0..n).map(|_| schema_with_params(3)).collect())
}

/// A batch of `n` schemas with diverse complexity.
///
/// The distribution within every 10 items is: 4 simple (3 params), 3 medium
/// (8 params), 2 long-description, 1 complex (5 fields, depth 2). Remaining
/// items cycle through the same pattern.
pub fn schema_batch_diverse(n: usize) -> Value {
    let items: Vec<Value> = (0..n)
        .map(|i| match i % 10 {
            0..4 => schema_with_params(3),
            4..7 => schema_with_params(8),
            7 | 8 => schema_long_description(),
            _ => schema_complex(5, 2),
        })
        .collect();
    Value::Array(items)
}

