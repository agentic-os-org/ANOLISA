/// A 3-level nested structure with a small tabular array — TOON's sweet spot.
pub fn toon_nested() -> Value {
    json!({
        "team": {
            "name": "core",
            "members": [
                { "id": 1, "role": "lead",  "years": 5 },
                { "id": 2, "role": "dev",   "years": 3 },
                { "id": 3, "role": "dev",   "years": 2 }
            ],
            "meta": { "region": "eu", "tier": { "level": 2, "name": "gold" } }
        }
    })
}

/// A larger uniform table of `rows` rows — TOON encodes these very compactly.
pub fn toon_table(rows: usize) -> Value {
    let items: Vec<Value> = (0..rows)
        .map(|i| json!({ "id": i, "name": format!("row-{i}"), "value": i * 7 }))
        .collect();
    json!({ "rows": items })
}
