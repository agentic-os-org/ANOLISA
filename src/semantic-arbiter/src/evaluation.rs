/// Model evaluation remains independent from the v1alpha1 recorded-clock check protocol.
pub const EVALUATION_API_VERSION: &str = "semantic-arbiter/v1alpha2";

/// Explicitly distinguishes model evaluation from deterministic checking.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum EvaluationMode {
    /// Real-time budget, frozen input, and an explicitly selected model adapter.
    ModelEvaluation,
}

/// Consumer-owned input; endpoint and credential configuration cannot come from evidence.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct EvaluationRequest {
    /// Exact model-evaluation protocol version.
    pub api_version: String,
    /// Immutable consumer request identity.
    pub request_id: String,
    /// Recorded-clock inputs are not accepted by this protocol.
    pub mode: EvaluationMode,
    /// Task, candidate, workspace and policy association.
    pub binding: Binding,
    /// Original Unix-millisecond timestamps and evidence limits.
    pub budget: Budget,
    /// Explicit enabled scenarios.
    pub scenarios: Vec<Scenario>,
    /// Authoritative task, or explicit absence.
    pub task: Option<Task>,
    /// Frozen operation and opaque resource identity.
    pub candidate: Candidate,
    /// Inline evidence with consumer-asserted provenance and Unix-millisecond clocks.
    pub evidence: Vec<Evidence>,
    /// Coverage omissions that semantic support cannot erase.
    pub gaps: Vec<EvidenceGap>,
}

impl<'a> From<&'a EvaluationRequest> for Input<'a> {
    fn from(value: &'a EvaluationRequest) -> Self {
        Self {
            request_id: &value.request_id,
            binding: &value.binding,
            budget: &value.budget,
            scenarios: &value.scenarios,
            task: value.task.as_ref(),
            candidate: &value.candidate,
            evidence: &value.evidence,
            gaps: &value.gaps,
        }
    }
}

impl EvaluationRequest {
    /// Decode closed, bounded input using the actual local clock.
    pub fn decode(bytes: &[u8]) -> Result<Self, ContractError> {
        let value: Self = crate::wire::decode(bytes)?;
        value.validate_at(Ingress::capture()?.now_ms())?;
        Ok(value)
    }

    fn validate_at(&self, now_ms: u64) -> Result<(), ContractError> {
        if self.api_version != EVALUATION_API_VERSION {
            return Err(ContractError::UnsupportedVersion);
        }
        validation::bounded(self)?;
        validation::context(&Input::from(self), now_ms)
    }
}

/// Public observations are inspectable, but cannot authenticate themselves.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct JudgmentTrace {
    /// Unit that owns the question and answer mapping.
    pub unit: Scenario,
    /// Revision of the deterministic interpretation rules.
    pub unit_revision: String,
    /// Versioned question identity.
    pub question_id: String,
    /// Experimental, uncalibrated acceptance threshold.
    pub threshold_ppm: u32,
    /// Validated raw and conservative normalized probability, when received.
    pub probability: Option<NoulProbability>,
    /// Sanitized adapter failure, never an upstream error body.
    pub error: Option<ModelError>,
    /// Whether a validated probability contributed to the final unit result.
    pub model_used: bool,
    /// Locally selected references; never generated by the model.
    pub evidence_refs: Vec<String>,
}

/// Advisory result; successful HTTP and a zero exit code do not authorize execution.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct EvaluationResponse {
    /// Exact model-evaluation protocol version.
    pub api_version: String,
    /// Echoed original request identity.
    pub request_id: String,
    /// Model evaluation, not deterministic checking.
    pub mode: EvaluationMode,
    /// Immutable input association.
    pub binding: Binding,
    /// Domain-separated digest of the exact typed input.
    pub input_digest: String,
    /// Digest of non-secret configuration and versioned question semantics.
    pub config_digest: String,
    /// Locally constructed adapter identity, not a server claim.
    pub backend: BackendIdentity,
    /// Probability transformation used for all observations.
    pub normalization_revision: String,
    /// Final validity check time in Unix milliseconds.
    pub evaluated_at_ms: u64,
    /// Total elapsed time including input preparation.
    pub elapsed_ms: u64,
    /// Whether this run invoked the selected backend.
    pub model_called: bool,
    /// Selected evidence, checked probabilities and thresholds per unit.
    pub judgments: Vec<JudgmentTrace>,
    /// Deterministically interpreted answers, including abstentions.
    pub answers: Vec<UnitAnswer>,
    /// Fixed action recommendations with no execution receipts.
    pub outcome: Outcome,
}

/// Retain this in process; wire-provided traces cannot substitute for it.
#[derive(Clone, Debug)]
pub struct EvaluationRecord {
    input_digest: String,
    config_digest: String,
    backend: BackendIdentity,
    started_at_ms: u64,
    completed_at_ms: u64,
    elapsed_ms: u64,
    exhausted: bool,
    reply: Option<Result<ModelReply, ModelError>>,
}

/// One result and its immutable, independently retained local observations.
#[derive(Clone, Debug)]
pub struct EvaluationRun {
    /// Serializable advisory output.
    pub response: EvaluationResponse,
    record: EvaluationRecord,
}

impl EvaluationRun {
    /// Obtain the local record needed to verify a returned response.
    pub fn record(&self) -> &EvaluationRecord {
        &self.record
    }
}

/// Shared evaluation pipeline; backend injection is a trusted in-process boundary.
pub struct Evaluator<B> {
    config: ModelConfig,
    backend: B,
}

impl<B: ModelBackend> Evaluator<B> {
    /// Bind a trusted adapter to its matching configuration, or an explicit test fixture.
    pub fn new(config: ModelConfig, backend: B) -> Result<Self, ContractError> {
        config.validate()?;
        let identity = backend.identity();
        let fixture =
            identity.kind == BackendKind::Fixture && identity.mode == BackendMode::Fixture;
        if !fixture && identity != config.identity() {
            return Err(ContractError::BindingMismatch);
        }
        Ok(Self { config, backend })
    }

    /// Evaluate frozen inputs under the original real-time deadline.
    pub async fn evaluate(
        &self,
        request: &EvaluationRequest,
    ) -> Result<EvaluationRun, ContractError> {
        self.evaluate_from_ingress(request, Ingress::capture()?)
            .await
    }

    /// Include time already spent by the caller reading input or preparing configuration.
    pub async fn evaluate_from_ingress(
        &self,
        request: &EvaluationRequest,
        ingress: Ingress,
    ) -> Result<EvaluationRun, ContractError> {
        let deadline = ingress.limit(&request.budget, self.config.timeout_ms);
        let started_at_ms = ingress.now_ms();
        request.validate_at(started_at_ms)?;
        if request.binding.config_revision != self.config.config_revision {
            return Err(ContractError::BindingMismatch);
        }
        let baseline = reference_answers(&Input::from(request), started_at_ms)?;
        let model_request = prepare_model_request(request, &baseline)?;
        let mut record = EvaluationRecord {
            input_digest: input_digest(request)?,
            config_digest: configuration_digest(&self.config)?,
            backend: self.backend.identity(),
            started_at_ms,
            completed_at_ms: started_at_ms,
            elapsed_ms: ingress.elapsed_ms(),
            exhausted: deadline.expired(),
            reply: None,
        };
        if !model_request.questions.is_empty() && !deadline.expired() {
            let reply = tokio::time::timeout_at(
                deadline.end,
                self.backend.infer(&model_request, deadline.end),
            )
            .await
            .unwrap_or(Err(ModelError::Timeout));
            record.reply =
                Some(reply.and_then(|reply| validate_model_reply(reply, &model_request)));
        }
        loop {
            record.completed_at_ms = deadline.ingress.now_ms();
            record.elapsed_ms = deadline.ingress.elapsed_ms();
            record.exhausted = deadline.expired();
            let response = derive_response(request, &self.config, &record)?;
            validation::bounded(&response)?;
            let now_ms = ingress.now_ms();
            let evidence_expired = response.answers.iter().any(|answer| {
                judgment::eligible(answer)
                    && request.evidence.iter().any(|evidence| {
                        answer.evidence_refs.contains(&evidence.id)
                            && evidence.valid_until_ms <= now_ms
                    })
            });
            if (!record.exhausted && deadline.expired()) || evidence_expired {
                continue;
            }
            return Ok(EvaluationRun { response, record });
        }
    }
}

/// Verify against a retained local record without making another model call.
pub fn validate_response(
    response: &EvaluationResponse,
    request: &EvaluationRequest,
    config: &ModelConfig,
    record: &EvaluationRecord,
) -> Result<(), ContractError> {
    config.validate()?;
    request.validate_at(record.started_at_ms)?;
    validation::bounded(response)?;
    if record.input_digest != input_digest(request)?
        || record.config_digest != configuration_digest(config)?
        || request.binding.config_revision != config.config_revision
    {
        return Err(ContractError::BindingMismatch);
    }
    let expected = derive_response(request, config, record)?;
    if *response != expected {
        return Err(ContractError::InvalidResponse);
    }
    Ok(())
}

/// Decode a response only with its original input, configuration and local record.
pub fn decode_response(
    bytes: &[u8],
    request: &EvaluationRequest,
    config: &ModelConfig,
    record: &EvaluationRecord,
) -> Result<EvaluationResponse, ContractError> {
    let response = crate::wire::decode(bytes)?;
    validate_response(&response, request, config, record)?;
    Ok(response)
}

/// Bind all typed input fields, not just identity labels.
pub fn input_digest(request: &EvaluationRequest) -> Result<String, ContractError> {
    digest(b"semantic-arbiter/v1alpha2\0evaluation-input\0", request)
}

fn configuration_digest(config: &ModelConfig) -> Result<String, ContractError> {
    let questions: Vec<_> = [Scenario::Preservation, Scenario::TaskScope]
        .into_iter()
        .map(|scenario| {
            let unit = judgment::unit(scenario);
            (unit.question_id(), unit.question())
        })
        .collect();
    digest(
        b"semantic-arbiter/v1alpha2\0evaluation-config\0",
        &(config, UNIT_REVISION, NORMALIZATION_VERSION, questions),
    )
}

fn digest(domain: &[u8], value: &impl Serialize) -> Result<String, ContractError> {
    let bytes = serde_json::to_vec(value).map_err(|_| ContractError::InvalidInput)?;
    let mut hash = Sha256::new();
    hash.update(domain);
    hash.update(bytes);
    Ok(format!("sha256:{:x}", hash.finalize()))
}

fn prepare_model_request(
    request: &EvaluationRequest,
    baseline: &[UnitAnswer],
) -> Result<ModelRequest, ContractError> {
    let questions = baseline
        .iter()
        .filter(|answer| judgment::eligible(answer))
        .map(|answer| {
            let unit = judgment::unit(answer.unit);
            (unit.question_id().to_string(), unit.question())
        })
        .collect();
    let evidence: Vec<_> = request
        .evidence
        .iter()
        .filter(|evidence| {
            baseline.iter().any(|answer| {
                judgment::eligible(answer) && answer.evidence_refs.contains(&evidence.id)
            })
        })
        .collect();
    let state = json!({
        "authoritative_task": request.task,
        "candidate": request.candidate,
        "evidence": evidence,
    });
    validation::bounded(&state)?;
    Ok(ModelRequest { state, questions })
}

fn validate_model_reply(
    reply: ModelReply,
    request: &ModelRequest,
) -> Result<ModelReply, ModelError> {
    if !reply.answers.keys().eq(request.questions.keys()) {
        return Err(ModelError::InvalidResponse);
    }
    Ok(reply)
}

fn derive_response(
    request: &EvaluationRequest,
    config: &ModelConfig,
    record: &EvaluationRecord,
) -> Result<EvaluationResponse, ContractError> {
    let input = Input::from(request);
    let initial = reference_answers(&input, record.started_at_ms)?;
    let baseline = reference_answers(&input, record.completed_at_ms)?;
    let mut judgments = Vec::new();
    let mut answers = Vec::new();
    let mut controls = Vec::new();
    for (before, base) in initial.iter().zip(baseline) {
        let unit = judgment::unit(base.unit);
        let threshold = match base.unit {
            Scenario::Preservation => config.thresholds.preservation_ppm,
            Scenario::TaskScope => config.thresholds.task_scope_ppm,
        };
        let requested = judgment::eligible(before) && record.reply.is_some();
        let (probability, error) = if requested {
            match &record.reply {
                Some(Ok(reply)) => (reply.answers.get(unit.question_id()).cloned(), None),
                Some(Err(error)) => (None, Some(*error)),
                None => (None, None),
            }
        } else {
            (None, None)
        };
        let used = !record.exhausted && judgment::eligible(&base) && probability.is_some();
        let (answer, control) = if !judgment::eligible(before) {
            (base.clone(), CandidateControl::Block)
        } else if record.exhausted {
            (
                judgment::unknown(&base, Reason::BudgetExceeded),
                CandidateControl::Nop,
            )
        } else if !judgment::eligible(&base) {
            (base.clone(), CandidateControl::Block)
        } else if let Some(probability) = &probability {
            let answer = unit.decide(&base, probability, threshold);
            let control = match answer.value {
                AnswerValue::Allow | AnswerValue::NeedsSnapshot => CandidateControl::Allow,
                AnswerValue::Preserve | AnswerValue::OutsideScope => CandidateControl::Block,
                AnswerValue::Unknown => CandidateControl::Nop,
            };
            (answer, control)
        } else {
            (
                judgment::unknown(&base, Reason::Undetermined),
                CandidateControl::Nop,
            )
        };
        judgments.push(JudgmentTrace {
            unit: base.unit,
            unit_revision: UNIT_REVISION.into(),
            question_id: unit.question_id().into(),
            threshold_ppm: threshold,
            probability,
            error,
            model_used: used,
            evidence_refs: base.evidence_refs,
        });
        answers.push(answer);
        controls.push(control);
    }
    let outcome = compose(&answers, &request.binding, controls);
    validation::outcome_for_input(&outcome, &input)?;
    Ok(EvaluationResponse {
        api_version: EVALUATION_API_VERSION.into(),
        request_id: request.request_id.clone(),
        mode: EvaluationMode::ModelEvaluation,
        binding: request.binding.clone(),
        input_digest: record.input_digest.clone(),
        config_digest: record.config_digest.clone(),
        backend: record.backend.clone(),
        normalization_revision: NORMALIZATION_VERSION.into(),
        evaluated_at_ms: record.completed_at_ms,
        elapsed_ms: record.elapsed_ms,
        model_called: record.reply.is_some(),
        judgments,
        answers,
        outcome,
    })
}
