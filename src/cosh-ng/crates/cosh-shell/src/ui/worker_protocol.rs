//! Host<->worker UI wire protocol: framing, owned messages, and typed DrawOps.
//!
//! The Host is the sole owner of the terminal, PTY, and session state. The
//! worker only receives typed render requests and returns typed [`DrawOp`]s; it
//! never sees raw input and never returns actions. Every field that is security
//! relevant (`session_nonce`, `worker_generation`, `frame_id`, `capture_id`) is
//! assigned by the Host and merely echoed by the worker, so the Host can validate
//! the echo on the way back.
//!
//! Wire layout of a single frame:
//!
//! ```text
//! | frame_len u32 LE | magic[4] | schema_version u16 LE | message_type u8 |
//! | payload_len u32 LE | session_nonce[16] | worker_generation u64 LE |
//! | frame_id u64 LE | payload… |
//! ```
//!
//! `frame_len` covers the fixed header plus payload, excluding its own prefix.
//! The outer length and fixed header are validated before the bounded payload is
//! deserialized. The payload is `serde_json`, so unknown enum variants (e.g. a
//! forged render style) fail closed on decode.

use serde::{Deserialize, Serialize};

/// Per-session random token, generated by the Host once per worker session.
pub type SessionNonce = [u8; 16];
/// Monotonic worker incarnation counter, assigned by the Host.
pub type WorkerGeneration = u64;
/// Monotonic frame counter, assigned by the Host per render request.
pub type FrameId = u64;
/// Optional capture correlation id, assigned by the Host.
pub type CaptureId = u64;

/// Four-byte magic that opens every fixed header (`CUI1`). Distinguishes this
/// schema from the ws-ckpt bincode framing and lets the Host reject foreign streams.
pub const PROTOCOL_MAGIC: [u8; 4] = *b"CUI1";

/// Current wire schema version. Bumped on any incompatible layout change.
pub const SCHEMA_VERSION: u16 = 2;

/// Byte length of the outer little-endian frame-length prefix.
pub const FRAME_LENGTH_PREFIX_LEN: usize = 4;

/// Byte length of the fixed header: `4 + 2 + 1 + 4 + 16 + 8 + 8`.
pub const PROTOCOL_HEADER_LEN: usize = 43;

/// Caller-supplied resource ceilings enforced while encoding, decoding, and
/// validating frames. Production values are deliberately selected outside this
/// protocol module after product approval.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ProtocolLimits {
    /// Maximum accepted `payload_len`. Checked before payload deserialization.
    pub max_payload_bytes: usize,
    /// Maximum number of [`DrawOp`]s a single [`PreparedFrame`] may carry.
    pub max_draw_ops: usize,
    /// Maximum UTF-8 byte length of a single [`DrawOp::Text`] run.
    pub max_text_bytes: usize,
}

/// Reasons a frame is rejected. Every variant is a hard, fail-closed refusal;
/// the decoder never silently truncates or coerces malformed input.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ProtocolError {
    /// Buffer is shorter than the length prefix or advertised complete frame.
    Truncated,
    /// Outer length prefix is shorter than the fixed protocol header.
    FrameTooSmall,
    /// Outer length prefix or fixed-header `payload_len` exceeds the caller's
    /// [`ProtocolLimits::max_payload_bytes`] ceiling.
    FrameTooLarge,
    /// Outer length does not equal fixed-header length plus `payload_len`.
    FrameLengthMismatch,
    /// A complete single-frame decoder received bytes after the framed message.
    TrailingBytes,
    /// Fixed-header magic is not [`PROTOCOL_MAGIC`].
    UnknownMagic,
    /// `schema_version` is not [`SCHEMA_VERSION`].
    UnsupportedVersion,
    /// `message_type` byte is not a known [`MessageType`] discriminant.
    UnknownMessageType,
    /// A known message type arrived on the wrong direction (e.g. a worker-only
    /// message decoded as a Host message).
    UnexpectedMessageType,
    /// Header nonce does not match the Host-generated session nonce.
    SessionNonceMismatch,
    /// Header generation does not match the Host-assigned worker generation.
    WorkerGenerationMismatch,
    /// Header frame id does not match the Host-assigned frame id.
    FrameIdMismatch,
    /// Payload bytes are not valid JSON for the routed message type.
    MalformedPayload(String),
}

impl std::fmt::Display for ProtocolError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ProtocolError::Truncated => write!(f, "frame is truncated: fewer bytes than declared"),
            ProtocolError::FrameTooSmall => {
                write!(f, "frame length is smaller than the fixed header")
            }
            ProtocolError::FrameTooLarge => {
                write!(f, "frame payload exceeds the caller-supplied limit")
            }
            ProtocolError::FrameLengthMismatch => {
                write!(f, "outer frame length does not match header payload_len")
            }
            ProtocolError::TrailingBytes => {
                write!(f, "single-frame input contains trailing bytes")
            }
            ProtocolError::UnknownMagic => write!(f, "frame magic does not match CUI1"),
            ProtocolError::UnsupportedVersion => {
                write!(f, "unsupported schema version (expected {SCHEMA_VERSION})")
            }
            ProtocolError::UnknownMessageType => write!(f, "unknown message-type discriminant"),
            ProtocolError::UnexpectedMessageType => {
                write!(f, "message-type is not valid for this decode direction")
            }
            ProtocolError::SessionNonceMismatch => {
                write!(f, "header session nonce does not match the active session")
            }
            ProtocolError::WorkerGenerationMismatch => {
                write!(
                    f,
                    "header worker generation does not match the active worker"
                )
            }
            ProtocolError::FrameIdMismatch => {
                write!(f, "header frame id does not match the requested frame")
            }
            ProtocolError::MalformedPayload(detail) => {
                write!(
                    f,
                    "payload is not valid JSON for its message type: {detail}"
                )
            }
        }
    }
}

impl std::error::Error for ProtocolError {}

/// Discriminates the payload carried by a frame. Encoded as a single byte in
/// the header; unknown bytes are rejected by [`MessageType::from_u8`].
#[repr(u8)]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum MessageType {
    /// Host -> worker handshake offer.
    Hello = 0,
    /// Host -> worker render request.
    Render = 1,
    /// Host -> worker acknowledgement that a frame was published.
    PublishedAck = 2,
    /// Host -> worker orderly shutdown.
    Shutdown = 3,
    /// worker -> Host handshake acceptance.
    Ready = 4,
    /// worker -> Host prepared frame of typed draw ops.
    PreparedFrame = 5,
    /// worker -> Host liveness ping.
    Heartbeat = 6,
    /// worker -> Host structured failure report.
    WorkerError = 7,
}

impl MessageType {
    /// Wire discriminant byte.
    #[must_use]
    pub const fn as_u8(self) -> u8 {
        self as u8
    }

    /// Decode a discriminant byte, failing closed on any unknown value.
    ///
    /// # Errors
    /// Returns [`ProtocolError::UnknownMessageType`] for bytes outside `0..=7`.
    pub const fn from_u8(value: u8) -> Result<Self, ProtocolError> {
        match value {
            0 => Ok(MessageType::Hello),
            1 => Ok(MessageType::Render),
            2 => Ok(MessageType::PublishedAck),
            3 => Ok(MessageType::Shutdown),
            4 => Ok(MessageType::Ready),
            5 => Ok(MessageType::PreparedFrame),
            6 => Ok(MessageType::Heartbeat),
            7 => Ok(MessageType::WorkerError),
            _ => Err(ProtocolError::UnknownMessageType),
        }
    }
}

/// Fixed-size frame header. Multi-byte integers are little-endian on the wire.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ProtocolHeader {
    /// Frame magic; must equal [`PROTOCOL_MAGIC`].
    pub magic: [u8; 4],
    /// Wire schema version; must equal [`SCHEMA_VERSION`].
    pub schema_version: u16,
    /// Routes the payload to the correct message type.
    pub message_type: MessageType,
    /// Length of the payload that follows the header.
    pub payload_len: u32,
    /// Host-generated per-session token; echoed unchanged by the worker.
    pub session_nonce: [u8; 16],
    /// Host-assigned worker incarnation; echoed unchanged by the worker.
    pub worker_generation: u64,
    /// Host-assigned frame counter; echoed unchanged by the worker.
    pub frame_id: u64,
}

/// Serialize a header into its fixed on-wire byte layout.
#[must_use]
pub fn encode_header(header: &ProtocolHeader) -> [u8; PROTOCOL_HEADER_LEN] {
    let mut out = [0u8; PROTOCOL_HEADER_LEN];
    out[0..4].copy_from_slice(&header.magic);
    out[4..6].copy_from_slice(&header.schema_version.to_le_bytes());
    out[6] = header.message_type.as_u8();
    out[7..11].copy_from_slice(&header.payload_len.to_le_bytes());
    out[11..27].copy_from_slice(&header.session_nonce);
    out[27..35].copy_from_slice(&header.worker_generation.to_le_bytes());
    out[35..43].copy_from_slice(&header.frame_id.to_le_bytes());
    out
}

/// Decode and validate a fixed header against caller-supplied `limits`.
///
/// The checks run in an order that lets the length gate reject an oversized
/// frame before any payload is read or allocated.
///
/// # Errors
/// Fails closed with [`ProtocolError`] on truncation, unknown magic,
/// unsupported version, unknown message type, or an oversized `payload_len`.
pub fn decode_header(
    bytes: &[u8],
    limits: &ProtocolLimits,
) -> Result<ProtocolHeader, ProtocolError> {
    if bytes.len() < PROTOCOL_HEADER_LEN {
        return Err(ProtocolError::Truncated);
    }

    let magic = [bytes[0], bytes[1], bytes[2], bytes[3]];
    if magic != PROTOCOL_MAGIC {
        return Err(ProtocolError::UnknownMagic);
    }

    let schema_version = u16::from_le_bytes([bytes[4], bytes[5]]);
    if schema_version != SCHEMA_VERSION {
        return Err(ProtocolError::UnsupportedVersion);
    }

    let message_type = MessageType::from_u8(bytes[6])?;

    let payload_len = u32::from_le_bytes([bytes[7], bytes[8], bytes[9], bytes[10]]);
    if payload_len as usize > limits.max_payload_bytes {
        return Err(ProtocolError::FrameTooLarge);
    }

    let mut session_nonce = [0u8; 16];
    session_nonce.copy_from_slice(&bytes[11..27]);
    let worker_generation = u64::from_le_bytes([
        bytes[27], bytes[28], bytes[29], bytes[30], bytes[31], bytes[32], bytes[33], bytes[34],
    ]);
    let frame_id = u64::from_le_bytes([
        bytes[35], bytes[36], bytes[37], bytes[38], bytes[39], bytes[40], bytes[41], bytes[42],
    ]);

    Ok(ProtocolHeader {
        magic,
        schema_version,
        message_type,
        payload_len,
        session_nonce,
        worker_generation,
        frame_id,
    })
}

/// Viewport the Host asks the worker to render into, in terminal cells.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct Viewport {
    /// Column count (width).
    pub columns: u16,
    /// Row count (height).
    pub rows: u16,
}

/// Geometry the worker reports for a prepared frame. The Host may recompute
/// this independently, so a worker cannot use it to move the real cursor
/// outside the viewport.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct FrameGeometry {
    /// Columns the frame was laid out for.
    pub columns: u16,
    /// Rows the frame was laid out for.
    pub rows: u16,
    /// Cursor column after the frame is applied.
    pub cursor_x: u16,
    /// Cursor row after the frame is applied.
    pub cursor_y: u16,
}

/// Whitelisted rendering styles. A closed enum by design: any style not listed
/// here cannot be expressed on the wire and unknown JSON tags fail to decode.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum RenderStyle {
    /// Reset all attributes.
    Reset,
    /// Bold weight.
    Bold,
    /// Dim/faint weight.
    Dim,
    /// Foreground color.
    Foreground(RenderColor),
    /// Background color.
    Background(RenderColor),
}

/// Whitelisted palette. Closed by design; no 256-color or truecolor escape
/// hatch is exposed to the worker.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum RenderColor {
    /// Terminal default color.
    Default,
    /// ANSI black.
    Black,
    /// ANSI red.
    Red,
    /// ANSI green.
    Green,
    /// ANSI yellow.
    Yellow,
    /// ANSI blue.
    Blue,
    /// ANSI magenta.
    Magenta,
    /// ANSI cyan.
    Cyan,
    /// ANSI white.
    White,
}

/// Host-owned identity of a frame. Used by the Host to correlate a worker's
/// echoed frame back to the request that produced it.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct FrameKey {
    /// Worker incarnation the frame belongs to.
    pub worker_generation: WorkerGeneration,
    /// Frame counter within the session.
    pub frame_id: FrameId,
    /// Optional capture correlation id.
    pub capture_id: Option<CaptureId>,
}

