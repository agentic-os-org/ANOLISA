/// worker -> Host structured failure report. Carries only a stable error code,
/// never free-form terminal output.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct WorkerError {
    /// Frame the failure is associated with, if any.
    pub frame_id: Option<FrameId>,
    /// Stable, machine-classifiable error code.
    pub code: String,
}

/// Every message the worker may send to the Host. Deliberately excludes any
/// action or raw-output variant: the worker returns typed frames only.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum WorkerMessage {
    /// See [`Ready`].
    Ready(Ready),
    /// See [`PreparedFrame`].
    PreparedFrame(PreparedFrame),
    /// See [`Heartbeat`].
    Heartbeat(Heartbeat),
    /// See [`WorkerError`].
    WorkerError(WorkerError),
}

impl WorkerMessage {
    /// Message-type discriminant for the header.
    #[must_use]
    pub const fn message_type(&self) -> MessageType {
        match self {
            WorkerMessage::Ready(_) => MessageType::Ready,
            WorkerMessage::PreparedFrame(_) => MessageType::PreparedFrame,
            WorkerMessage::Heartbeat(_) => MessageType::Heartbeat,
            WorkerMessage::WorkerError(_) => MessageType::WorkerError,
        }
    }
}

/// One whitelisted drawing primitive. There is intentionally no raw-ANSI or
/// escape-sequence variant; the Host reconstructs terminal output from these.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum DrawOp {
    /// Clear a rectangle to blanks.
    ClearRect {
        /// Left column.
        x: u16,
        /// Top row.
        y: u16,
        /// Width in cells.
        width: u16,
        /// Height in cells.
        height: u16,
    },
    /// Move the drawing cursor.
    MoveTo {
        /// Target column.
        x: u16,
        /// Target row.
        y: u16,
    },
    /// Set the active style for subsequent [`DrawOp::Text`].
    SetStyle(RenderStyle),
    /// Emit plain text at the current cursor. Must not contain control chars.
    Text(String),
    /// Show or hide the cursor.
    CursorVisible(bool),
}

/// A frame of typed draw ops produced by the worker. The `worker_generation`
/// and `frame_id` fields echo the Host-assigned header values so the Host can
/// cross-check the echo; `geometry` is advisory and re-checked by the Host.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct PreparedFrame {
    /// Echoed worker incarnation.
    pub worker_generation: u64,
    /// Echoed frame counter.
    pub frame_id: u64,
    /// Echoed capture correlation id.
    pub capture_id: Option<u64>,
    /// Whitelisted draw ops, applied in order.
    pub draw_ops: Vec<DrawOp>,
    /// Advisory geometry after the ops are applied.
    pub geometry: FrameGeometry,
    /// Whether the frame repaints the whole viewport.
    pub full_repaint: bool,
}

impl PreparedFrame {
    /// Host-owned identity of this frame, derived from the echoed fields.
    #[must_use]
    pub const fn frame_key(&self) -> FrameKey {
        FrameKey {
            worker_generation: self.worker_generation,
            frame_id: self.frame_id,
            capture_id: self.capture_id,
        }
    }
}

