/// Presentation language chosen by the Host. The worker never negotiates it.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum UiLanguage {
    /// English labels.
    En,
    /// Simplified Chinese labels.
    Zh,
}

/// One action the user can focus on an approval card. Ordered by the Host; the
/// worker only renders and never reorders or extends the set.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum ApprovalActionView {
    /// Approve this single request.
    Approve,
    /// Deny this single request.
    Deny,
    /// Expand or collapse the request details.
    Details,
}

/// Read-only projection of one pending approval, frozen by the Host.
///
/// Deliberately excludes queue, turn and hook state: those are outside the
/// slice eligibility predicate and must not cross the process boundary.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub struct ApprovalCardView {
    /// Host projection revision; strictly monotonic per session.
    pub revision: u64,
    /// Label language.
    pub language: UiLanguage,
    /// Short display identity shown in the card header.
    pub display_id: String,
    /// Tool kind label, e.g. `Bash`.
    pub kind: String,
    /// Risk label, e.g. `high`.
    pub risk: String,
    /// Human-readable risk reason, e.g. `write redirection`.
    pub reason: String,
    /// Subject line of the request.
    pub subject: String,
    /// Already-redacted command or argument preview.
    pub preview: String,
    /// Canonical tool label.
    pub label: String,
    /// Actions to render, in focus order.
    pub actions: Vec<ApprovalActionView>,
    /// Action that currently holds focus.
    pub selected: ApprovalActionView,
    /// Whether the details section is expanded.
    pub expanded: bool,
    /// Set when the Host can no longer recover this presentation.
    pub irrecoverable: bool,
}

/// Typed, Host-owned view state handed to the worker. The worker only ever
/// receives typed views, never raw input bytes.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
pub enum RenderView {
    /// Empty view (initial and idle state).
    Empty(EmptyRenderView),
    /// One pending approval card.
    ApprovalCard(ApprovalCardView),
}

