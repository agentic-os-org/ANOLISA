//! Host-owned input router: the single authority that publishes a capture to a
//! worker frame and consumes exactly one Host input action against it.
//!
//! The Host permanently owns raw input and card actions; nothing in this module
//! serializes input or actions to the worker. A published capture is identified
//! by three *independent* Host epochs — `worker_generation`, `input_epoch`, and
//! `prompt_evidence_epoch` — plus the frame/capture ids and a monotonic
//! `publish_seq`. An action is only honored when it echoes the live token on
//! every field, arrives strictly after the publish cutover, and has not already
//! been consumed. Replays and stale bytes fail closed.

use crate::ui::worker_protocol::{FrameGeometry, FrameKey};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::{Arc, Mutex};

#[cfg(test)]
mod tests;

/// Capability minted when the Host publishes a capture to a worker frame. It
/// snapshots the three Host epochs so a later action can be validated against
/// the exact context that was live at publish time.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct PublishedCaptureToken {
    /// Per-session random token, generated by the Host once per worker session.
    pub session_nonce: [u8; 16],
    /// Worker incarnation the capture belongs to.
    pub worker_generation: u64,
    /// Input-ownership epoch; advances when the Host resets input routing.
    pub input_epoch: u64,
    /// Prompt/evidence epoch; advances when the prompt evidence context changes.
    pub prompt_evidence_epoch: u64,
    /// Frame that carried the capture.
    pub frame_id: u64,
    /// Capture correlation id assigned by the Host.
    pub capture_id: u64,
    /// Input-sequence sample taken at commit; actions must be strictly newer.
    pub publish_seq: u64,
}

/// Closed set of card actions the Host may derive from raw input. A closed enum
/// by design: the worker never proposes actions, so no open-ended variant is
/// exposed.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CardAction {
    /// Approve the presented card.
    Approve,
    /// Deny the presented card.
    Deny,
    /// Cancel/dismiss the presented card.
    Cancel,
    /// Select an option by index.
    Select {
        /// Zero-based option index.
        index: usize,
    },
    /// Submit the card's current selection or buffer.
    Submit,
    /// Scroll the card by a signed row delta.
    Scroll {
        /// Signed row delta (negative scrolls up).
        delta: i16,
    },
}

/// A Host input action addressed to a published capture. `token` echoes the
/// capability, `input_seq` is the sequence stamp of the bytes that produced the
/// action, and `action` is the derived [`CardAction`].
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct HostInputAction {
    /// Capability the action claims to act on.
    pub token: PublishedCaptureToken,
    /// Sequence stamp of the input bytes behind this action.
    pub input_seq: u64,
    /// Action derived by the Host from those bytes.
    pub action: CardAction,
}

/// Who currently owns terminal input, as observed by the router.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CaptureAuthority {
    /// The legacy in-process input path owns input (no capture published).
    Legacy,
    /// A published capture owns input; the token is its identity.
    Published(PublishedCaptureToken),
}

/// Atomic reader snapshot of the current input-routing boundary.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct InputRouteSnapshot {
    /// Monotonic ownership cutover counter.
    pub epoch: u64,
    /// Current owner, or `None` while a frame is publishing.
    pub authority: Option<CaptureAuthority>,
}

/// Cloneable observer for sampling input ownership around a blocking read.
#[derive(Clone)]
pub struct InputRouteTracker(Arc<Mutex<InputRouteSnapshot>>);

impl InputRouteTracker {
    /// Returns one consistent epoch/authority snapshot.
    pub fn snapshot(&self) -> InputRouteSnapshot {
        *self
            .0
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }

    fn transition(&self, authority: Option<CaptureAuthority>) {
        let mut snapshot = self
            .0
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        snapshot.epoch = snapshot.epoch.wrapping_add(1);
        snapshot.authority = authority;
    }
}

/// Monotonic, cloneable Host input sequence. Every raw-input read stamps bytes
/// with [`InputSequence::next`], giving a single global ordering the router uses
/// to reject bytes that predate a publish cutover. Clones share one counter.
#[derive(Clone)]
pub struct InputSequence(Arc<AtomicU64>);

impl InputSequence {
    /// Creates a fresh sequence starting before the first stamp (0).
    pub fn new() -> Self {
        Self(Arc::new(AtomicU64::new(0)))
    }

    /// Stamps the next input and returns its strictly-increasing value.
    // Named `next` per the Host contract; it is not an `Iterator`.
    #[allow(clippy::should_implement_trait)]
    pub fn next(&self) -> u64 {
        self.0.fetch_add(1, Ordering::SeqCst).wrapping_add(1)
    }

    /// Returns the most recently stamped value without advancing.
    pub fn current(&self) -> u64 {
        self.0.load(Ordering::SeqCst)
    }
}

impl Default for InputSequence {
    fn default() -> Self {
        Self::new()
    }
}

/// Handle returned by [`InputRouter::begin_publish`] and consumed by
/// [`InputRouter::commit_publish`] or [`InputRouter::abort_publish`]. It is
/// deliberately neither `Copy` nor `Clone`: the borrow checker moves it into
/// exactly one resolver, and the router additionally only acts on a guard while
/// it is still `Publishing`. Together these make a publish resolve exactly once
/// — begin->abort->commit, double-commit, and double-abort all fail closed and
/// mint no token.
#[derive(Debug, Eq, PartialEq)]
pub struct PublishGuard {
    /// Frame being published.
    pub frame_id: u64,
    /// Capture id, if the frame carries one. `None` publishes no capture.
    pub capture_id: Option<u64>,
    /// Input-sequence lower bound sampled when the publish began.
    pub input_barrier: u64,
}

/// Reasons a Host input action is refused. Every variant is a fail-closed
/// refusal; the router never silently coerces or accepts a mismatched action.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CaptureError {
    /// No capture is published (idle legacy owner or mid-publish), so no card
    /// owns input.
    NoPublishedCapture,
    /// The action's token does not match the live capture on at least one
    /// identity field (nonce, the three epochs, frame id, or capture id).
    IdentityMismatch,
    /// `input_seq` is not strictly greater than `publish_seq`: the bytes were
    /// sampled at or before the publish cutover.
    StaleInput,
    /// The capture was already consumed; replays never re-fire.
    AlreadyConsumed,
}

impl std::fmt::Display for CaptureError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            CaptureError::NoPublishedCapture => {
                write!(f, "no capture is currently published")
            }
            CaptureError::IdentityMismatch => {
                write!(f, "action token does not match the published capture")
            }
            CaptureError::StaleInput => {
                write!(
                    f,
                    "input sequence is not strictly after the publish cutover"
                )
            }
            CaptureError::AlreadyConsumed => {
                write!(f, "published capture was already consumed")
            }
        }
    }
}

impl std::error::Error for CaptureError {}

/// Internal publish lifecycle. Kept private so `Publishing` (bytes belong to no
/// owner) cannot be observed as a public `CaptureAuthority` variant.
enum PublishState {
    /// No published capture; the legacy in-process owner handles input.
    Legacy,
    /// A publish is in flight. Capture is revoked and input has no owner until
    /// the guard commits or aborts.
    Publishing,
    /// A capture is published. `consumed` flips true after the one accepted
    /// action so replays are refused.
    Published {
        token: PublishedCaptureToken,
        geometry: FrameGeometry,
        consumed: bool,
    },
}

/// The single Host-owned router binding raw input to at most one published
/// capture at a time. The three epochs are held as distinct fields so advancing
/// one never implicitly advances another.
pub struct InputRouter {
    session_nonce: [u8; 16],
    worker_generation: u64,
    input_epoch: u64,
    prompt_evidence_epoch: u64,
    input_sequence: InputSequence,
    route_tracker: InputRouteTracker,
    state: PublishState,
}

impl InputRouter {
    /// Creates a router for the given Host session nonce and the three
    /// independent epochs. It starts with no published capture (legacy owner)
    /// and its own fresh input sequence.
    pub fn new(
        session_nonce: [u8; 16],
        worker_generation: u64,
        input_epoch: u64,
        prompt_evidence_epoch: u64,
    ) -> Self {
        Self {
            session_nonce,
            worker_generation,
            input_epoch,
            prompt_evidence_epoch,
            input_sequence: InputSequence::new(),
            route_tracker: InputRouteTracker(Arc::new(Mutex::new(InputRouteSnapshot {
                epoch: 0,
                authority: Some(CaptureAuthority::Legacy),
            }))),
            state: PublishState::Legacy,
        }
    }

    /// Returns a clone of the Host input sequence so readers stamp bytes on the
    /// same counter the router validates against.
    pub fn input_sequence(&self) -> InputSequence {
        self.input_sequence.clone()
    }

    /// Returns a cloneable tracker for sampling routing cutovers around reads.
    pub fn route_tracker(&self) -> InputRouteTracker {
        self.route_tracker.clone()
    }

    /// Current input owner: `Legacy`, `Published(token)`, or `None` while a
    /// publish is in flight (bytes belong to no owner).
    pub fn authority(&self) -> Option<CaptureAuthority> {
        match &self.state {
            PublishState::Legacy => Some(CaptureAuthority::Legacy),
            PublishState::Publishing | PublishState::Published { consumed: true, .. } => None,
            PublishState::Published {
                token,
                consumed: false,
                ..
            } => Some(CaptureAuthority::Published(*token)),
        }
    }

    /// Geometry of the currently published frame, if any.
    pub fn published_geometry(&self) -> Option<FrameGeometry> {
        match &self.state {
            PublishState::Published { geometry, .. } => Some(*geometry),
            _ => None,
        }
    }

    /// Begins publishing `key`. This immediately revokes any live capture:
    /// until the returned guard commits or aborts, input belongs to no owner.
    /// `input_barrier` is the input-sequence value at publish start.
    pub fn begin_publish(&mut self, key: FrameKey, input_barrier: u64) -> PublishGuard {
        self.route_tracker.transition(None);
        self.state = PublishState::Publishing;
        PublishGuard {
            frame_id: key.frame_id,
            capture_id: key.capture_id,
            input_barrier,
        }
    }

    /// Commits a publish, taking a second input-sequence sample (`publish_seq`).
    /// Returns `Some(token)` only when the router is still mid-publish *and* the
    /// guarded frame carries a capture id; otherwise input returns to (or stays
    /// with) the legacy owner and `None` is returned.
    ///
    /// A stale guard whose publish already resolved (after a prior commit or
    /// abort) finds the router out of `Publishing` and mints nothing, so
    /// begin->abort->commit and double-commit both fail closed.
    pub fn commit_publish(
        &mut self,
        guard: PublishGuard,
        publish_seq: u64,
        geometry: FrameGeometry,
    ) -> Option<PublishedCaptureToken> {
        // Resolve-exactly-once: only an in-flight publish may commit. A stale
        // guard presented after the publish already resolved mints nothing and
        // leaves the current state untouched.
        if !matches!(self.state, PublishState::Publishing) {
            return None;
        }
        let Some(capture_id) = guard.capture_id else {
            // A frame without a capture owns no input.
            self.state = PublishState::Legacy;
            self.route_tracker
                .transition(Some(CaptureAuthority::Legacy));
            return None;
        };
        // Clamp the cutover up to the begin-publish barrier so bytes sampled
        // before the publish can never be accepted, even under a stale sample.
        let publish_seq = publish_seq.max(guard.input_barrier);
        let token = PublishedCaptureToken {
            session_nonce: self.session_nonce,
            worker_generation: self.worker_generation,
            input_epoch: self.input_epoch,
            prompt_evidence_epoch: self.prompt_evidence_epoch,
            frame_id: guard.frame_id,
            capture_id,
            publish_seq,
        };
        self.state = PublishState::Published {
            token,
            geometry,
            consumed: false,
        };
        self.route_tracker
            .transition(Some(CaptureAuthority::Published(token)));
        Some(token)
    }

    /// Aborts an in-flight publish, returning input to the legacy owner without
    /// minting a token. A no-op when the router is not currently `Publishing`,
    /// so a stale guard presented after a prior commit or abort cannot revoke a
    /// live published capture (abort-after-commit and double-abort fail closed).
    pub fn abort_publish(&mut self, guard: PublishGuard) {
        let _ = guard;
        if matches!(self.state, PublishState::Publishing) {
            self.state = PublishState::Legacy;
            self.route_tracker
                .transition(Some(CaptureAuthority::Legacy));
        }
    }

    /// Consumes exactly one Host input action against the published capture.
    ///
    /// # Errors
    /// - [`CaptureError::NoPublishedCapture`] when no capture is published.
    /// - [`CaptureError::AlreadyConsumed`] when the capture was already consumed.
    /// - [`CaptureError::IdentityMismatch`] when the token differs on any
    ///   identity field.
    /// - [`CaptureError::StaleInput`] when `input_seq <= publish_seq`.
    pub fn consume_once(&mut self, action: HostInputAction) -> Result<CardAction, CaptureError> {
        let PublishState::Published {
            token, consumed, ..
        } = &mut self.state
        else {
            return Err(CaptureError::NoPublishedCapture);
        };
        if *consumed {
            return Err(CaptureError::AlreadyConsumed);
        }
        let presented = &action.token;
        // Each identity field is checked separately so every field is
        // independently load-bearing (see the per-field rejection tests).
        if presented.session_nonce != token.session_nonce {
            return Err(CaptureError::IdentityMismatch);
        }
        if presented.worker_generation != token.worker_generation {
            return Err(CaptureError::IdentityMismatch);
        }
        if presented.input_epoch != token.input_epoch {
            return Err(CaptureError::IdentityMismatch);
        }
        if presented.prompt_evidence_epoch != token.prompt_evidence_epoch {
            return Err(CaptureError::IdentityMismatch);
        }
        if presented.frame_id != token.frame_id {
            return Err(CaptureError::IdentityMismatch);
        }
        if presented.capture_id != token.capture_id {
            return Err(CaptureError::IdentityMismatch);
        }
        // Bytes must be strictly newer than the publish cutover.
        if action.input_seq <= token.publish_seq {
            return Err(CaptureError::StaleInput);
        }
        *consumed = true;
        self.route_tracker.transition(None);
        Ok(action.action)
    }
}
